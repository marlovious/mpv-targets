//! The public protocol surface for `mpv-targets`.
//!
//! This crate deliberately owns the wire types used by both the daemon and its
//! clients.  Keeping the model here makes it impossible for the operator client
//! to acquire a private daemon protocol.

pub mod answer;
pub mod client;
pub mod config;
pub mod protocol;
mod tls;

pub use answer::{AnswerError, AnswerFile, AnswerTarget, AnswerTls, ServiceAnswer};
pub use client::{
    AddTargetResult, ChannelCatalog, ChannelMutationResult, ClientError, ClientOptions,
    DisconnectReason, EnableResult, LifecycleResult, LoadMode, LoopState, PlaylistItem,
    RemoteClient, RemoveTargetResult, RenameTargetResult, TargetClient, TargetStatus, Track,
    target_status,
};

/// The ordinary target baseline used when no source configuration is supplied.
pub fn base_mpv_conf(start_paused: bool, start_muted: bool, volume: f64) -> String {
    format!(
        "# Generated by mpv-targets. Edit this target-local file for advanced mpv settings.\nforce-window=yes\nidle=yes\nreally-quiet=yes\npause={}\nvolume={}\nmute={}\ndirectory-mode=recursive\n",
        if start_paused { "yes" } else { "no" },
        volume,
        if start_muted { "yes" } else { "no" },
    )
}

/// The canonical short label for a channel catalog value.
pub fn channel_display_name(channel: &str) -> &str {
    channel.rsplit('/').next().unwrap_or(channel)
}
pub use config::{ConfigError, DaemonConfig, TargetConfig, TlsConfig};
pub use protocol::{
    ErrorCode, ErrorResponse, Event, Health, HealthState, MediaEndReason, MpvOperation, Operation,
    Request, Response, ServiceOperation, Snapshot, TargetChanged, TargetRecord, TargetState,
};
pub use tls::{TlsMaterialError, server_tls_config};

#[cfg(test)]
mod tests {
    use super::channel_display_name;

    #[test]
    fn channel_display_uses_only_the_catalog_filename() {
        assert_eq!(
            channel_display_name("/srv/channels/cameras.m3u8"),
            "cameras.m3u8"
        );
    }
}
